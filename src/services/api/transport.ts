import { apiRequest, type ApiRequestOptions } from './http';
import { collectionApi } from './resource';

export type DriverStatus = 'Available' | 'On Delivery' | 'Returning' | 'Off Duty';
export type VehicleType = 'Flatbed' | 'Lowboy' | 'Crane Truck' | 'Recovery';
export type VehicleStatus = 'Available' | 'On Route' | 'Maintenance' | 'Offline';
export type TransportJobStatusValue =
  'Scheduled' | 'Loading' | 'In Transit' | 'Delivered' | 'Returning' | 'Completed' | 'Cancelled';
export type TransportShiftValue = 'Morning' | 'Evening';
export type TransportTypeCodeValue = 'D' | 'O' | 'T' | 'T2';

export interface DriverDto {
  id: string; branchId: string; userId: string | null; name: string; phone: string; licenseNo: string;
  licenseExpiresOn: string; status: DriverStatus; createdAt: string; updatedAt: string; rowVersion: number;
}
export interface DriverCreate {
  branchId: string; userId?: string | null; name: string; phone: string; licenseNo: string; licenseExpiresOn: string;
  status?: DriverStatus;
}
export type DriverUpdate = Partial<DriverCreate>;
export interface DriverFilters { branchId?: string; status?: DriverStatus; q?: string }

export interface TransportVehicleDto {
  id: string; branchId: string; registrationNo: string; vehicleType: VehicleType; capacityKg: string;
  status: VehicleStatus; createdAt: string; updatedAt: string; rowVersion: number;
}
export interface TransportVehicleCreate {
  branchId: string; registrationNo: string; vehicleType: VehicleType; capacityKg: string | number; status?: VehicleStatus;
}
export type TransportVehicleUpdate = Partial<TransportVehicleCreate>;
export interface TransportVehicleFilters { branchId?: string; status?: VehicleStatus; vehicleType?: VehicleType; q?: string }

export interface TransportJobDto {
  id: string; reference: string; branchId: string; machineId: string; bookingId: string | null; quotationId: string | null;
  collectionNoteId: string | null; driverId: string | null; vehicleId: string | null; plannerName: string;
  scheduleDate: string; shift: TransportShiftValue; transportTeam: string; scheduleSerial: number;
  fleetNoSnapshot: string; origin: string; destination: string; transportText: string; typeCode: TransportTypeCodeValue;
  contactText: string; salespersonCode: string; clientText: string; scheduledAt: string; status: TransportJobStatusValue;
  distanceKm: string | null; chargeToCustomer: string | null; internalCost: string | null; currencyCode: string;
  autoGenerated: boolean; sourceKey: string | null; remarks: string | null; createdAt: string; updatedAt: string;
  rowVersion: number;
}
export interface TransportJobCreate {
  machineId: string; bookingId?: string | null; quotationId?: string | null; currencyCode?: string;
  plannerName: string; scheduleDate: string; shift: TransportShiftValue; transportTeam: string; scheduleSerial: number;
  origin: string; destination: string; transportText: string; typeCode: TransportTypeCodeValue; contactText: string;
  salespersonCode: string; clientText: string; scheduledAt: string;
  driverId?: string | null; vehicleId?: string | null; distanceKm?: string | number | null;
  chargeToCustomer?: string | number | null; internalCost?: string | number | null; remarks?: string | null;
}
/** Machine, booking and quotation are fixed at creation. */
export type TransportJobUpdate = Partial<Omit<TransportJobCreate, 'machineId' | 'bookingId' | 'quotationId' | 'currencyCode'>>;
export interface TransportJobFilters {
  status?: TransportJobStatusValue; machineId?: string; bookingId?: string; scheduleDate?: string; branchId?: string;
  autoGenerated?: boolean; q?: string;
}

/** `/api/v1/drivers`. */
export const driversApi = collectionApi<DriverDto, DriverCreate, DriverUpdate, DriverFilters>('/drivers');

/** `/api/v1/transport-vehicles`. A duplicate registration answers 409 DUPLICATE. */
export const transportVehiclesApi =
  collectionApi<TransportVehicleDto, TransportVehicleCreate, TransportVehicleUpdate, TransportVehicleFilters>('/transport-vehicles');

/** `/api/v1/transport-jobs`. Manual and collection-generated jobs share this list. */
export const transportJobsApi = {
  ...collectionApi<TransportJobDto, TransportJobCreate, TransportJobUpdate, TransportJobFilters>('/transport-jobs'),
  /** Scheduled -> Loading -> In Transit -> Delivered -> Returning -> Completed; Cancelled from any non-final status. */
  changeStatus: (
    id: string, rowVersion: number, input: { status: TransportJobStatusValue; reason?: string },
    opts: Pick<ApiRequestOptions, 'signal'> = {},
  ) =>
    apiRequest<TransportJobDto>(`/transport-jobs/${encodeURIComponent(id)}/status`, {
      method: 'POST', body: input, rowVersion, ...opts,
    }),
};
