// Maps the transport API records to the shapes the transport, tracking and truck screens render.
import type { Driver, Truck, TransportForm, TransportJobRecord, TransportJobView, TransportTypeCode } from '@/types/transport';
import type { Machine } from '@/types/machine';
import { kindOfType } from '@/services/transportCore';
import type { DriverDto, TransportJobCreate, TransportJobDto, TransportVehicleDto } from './transport';

/** A transport job as the screens read it: the legacy view plus the server row version. */
export interface ApiTransportJobView extends TransportJobView {
  rowVersion: number;
  /** The driver and vehicle ids as stored (null when unassigned). */
  driverRefId: string | null;
  vehicleRefId: string | null;
  autoGenerated: boolean;
}

export interface TransportViewContext {
  orgId: string;
  machines: ReadonlyMap<string, Machine>;
  drivers: ReadonlyMap<string, DriverDto>;
  vehicles: ReadonlyMap<string, TransportVehicleDto>;
  branchNames: ReadonlyMap<string, string>;
}

const pad = (n: number) => String(n).padStart(2, '0');

/** `HH:mm` of an ISO timestamp in the browser's time zone (the zone the form time was entered in). */
export function localTimeOf(iso: string): string {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? '' : `${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

/** The ISO timestamp (with offset) for a date and a `HH:mm` time entered in the browser's time zone. */
export function scheduledAtFrom(date: string, time: string): string {
  const hhmm = time.length === 5 ? `${time}:00` : time;
  const d = new Date(`${date}T${hhmm}`);
  if (Number.isNaN(d.getTime())) throw new Error('Date or time is not valid');
  return d.toISOString();
}

const num = (v: string | null): number | undefined => (v === null || v === '' || Number.isNaN(Number(v)) ? undefined : Number(v));

export function transportJobFromDto(dto: TransportJobDto, ctx: TransportViewContext): ApiTransportJobView {
  const machine = ctx.machines.get(dto.machineId);
  const driver = dto.driverId ? ctx.drivers.get(dto.driverId) : undefined;
  const vehicle = dto.vehicleId ? ctx.vehicles.get(dto.vehicleId) : undefined;
  const ref13: TransportForm = {
    plannerName: dto.plannerName,
    date: dto.scheduleDate,
    shift: dto.shift,
    transportTeam: dto.transportTeam,
    srNo: dto.scheduleSerial,
    fleet: dto.fleetNoSnapshot,
    from: dto.origin,
    to: dto.destination,
    transport: dto.transportText,
    type: dto.typeCode,
    contact: dto.contactText,
    sales: dto.salespersonCode,
    client: dto.clientText,
    time: localTimeOf(dto.scheduledAt),
    remarks: dto.remarks ?? '',
  };
  return {
    id: dto.id,
    createdAt: dto.createdAt,
    updatedAt: dto.updatedAt,
    orgId: ctx.orgId,
    reference: dto.reference,
    machineId: dto.machineId,
    assetNumber: dto.fleetNoSnapshot,
    machineModel: machine ? `${machine.make} ${machine.model}`.trim() : '',
    branchId: dto.branchId,
    branchName: ctx.branchNames.get(dto.branchId) ?? '',
    driverId: dto.driverId ?? '',
    driverName: driver?.name ?? '',
    truckId: dto.vehicleId ?? '',
    truckRegistration: vehicle?.registrationNo ?? dto.transportText,
    origin: dto.origin,
    destination: dto.destination,
    scheduledTime: dto.scheduledAt,
    status: dto.status,
    distance: num(dto.distanceKm),
    bookingRef: dto.bookingId ?? undefined,
    type: kindOfType(dto.typeCode as TransportTypeCode),
    notes: dto.remarks ?? undefined,
    customerName: dto.clientText,
    chargeToCustomer: num(dto.chargeToCustomer) ?? 0,
    internalCost: num(dto.internalCost) ?? 0,
    quotationId: dto.quotationId ?? undefined,
    collectionNoteId: dto.collectionNoteId ?? undefined,
    ref13,
    rowVersion: dto.rowVersion,
    driverRefId: dto.driverId,
    vehicleRefId: dto.vehicleId,
    autoGenerated: dto.autoGenerated,
  };
}

/** The in-memory record the retained legacy readers (kanban, TRIPBASE report) use. */
export function transportRecordFromView(v: ApiTransportJobView): TransportJobRecord {
  const f = v.ref13!;
  return {
    ...f,
    id: v.id,
    orgId: v.orgId,
    reference: v.reference,
    status: v.status,
    machineId: v.machineId,
    branchId: v.branchId,
    branchName: v.branchName,
    driverId: v.driverId || undefined,
    driverName: v.driverName || undefined,
    truckId: v.truckId || undefined,
    quotationId: v.quotationId,
    bookingId: v.bookingRef,
    collectionNoteId: v.collectionNoteId,
    autoGenerated: v.autoGenerated,
    createdAt: v.createdAt,
    updatedAt: v.updatedAt,
  };
}

export function driverFromDto(dto: DriverDto, branchNames: ReadonlyMap<string, string>): Driver {
  return {
    id: dto.id,
    name: dto.name,
    phone: dto.phone,
    licenseNumber: dto.licenseNo,
    licenseExpiry: dto.licenseExpiresOn,
    branchId: dto.branchId,
    branchName: branchNames.get(dto.branchId) ?? '',
    status: dto.status,
    rating: 0,
    totalDeliveries: 0,
  };
}

export interface ApiTruck extends Truck {
  capacityKg: string;
}

export function truckFromDto(dto: TransportVehicleDto, branchNames: ReadonlyMap<string, string>): ApiTruck {
  return {
    id: dto.id,
    registration: dto.registrationNo,
    type: dto.vehicleType,
    capacity: Number(dto.capacityKg) / 1000,
    capacityKg: dto.capacityKg,
    branchId: dto.branchId,
    branchName: branchNames.get(dto.branchId) ?? '',
    status: dto.status,
  };
}

/** The create body for the 15 REF-13 fields. `machineId` is the machine picked for the Fleet field. */
export function transportCreateFromForm(form: TransportForm, machineId: string): TransportJobCreate {
  const remarks = form.remarks?.trim();
  return {
    machineId,
    plannerName: form.plannerName.trim(),
    scheduleDate: form.date,
    shift: form.shift,
    transportTeam: form.transportTeam.trim(),
    scheduleSerial: form.srNo,
    origin: form.from.trim(),
    destination: form.to.trim(),
    transportText: form.transport.trim(),
    typeCode: form.type,
    contactText: form.contact.trim(),
    salespersonCode: form.sales.trim(),
    clientText: form.client.trim(),
    scheduledAt: scheduledAtFrom(form.date, form.time),
    remarks: remarks ? remarks : null,
  };
}
