const change = (el: HTMLElement, value: string) => fireEvent.change(el, { target: { value } });

async function panel(): Promise<HTMLElement> {
  const title = await screen.findByRole('heading', { level: 2, name: /^TJ-/ });
  return title.closest('.fixed') as HTMLElement;
}

describe('TransportJobDialog', () => {
  it('shows field-level messages and creates nothing when required fields are empty', async () => {
    const onClose = vi.fn();
    render(<TransportJobDialog open onClose={onClose} />);
    fireEvent.click(screen.getByRole('button', { name: 'Create Transport Job' }));
    expect(await screen.findByText('Planner name required')).toBeTruthy();
    expect(screen.getByText('Delivery destination required')).toBeTruthy();
    expect(createMutateAsync).not.toHaveBeenCalled();
    expect(onClose).not.toHaveBeenCalled();
  });

  it('sends the 15 REF-13 fields with the selected machine and one submission', async () => {
    createMutateAsync.mockResolvedValue({ id: 'j-1' });
    const onClose = vi.fn();
    render(<TransportJobDialog open onClose={onClose} />);
    change(screen.getByPlaceholderText('e.g. Prashanth'), 'Prashanth');
    change(screen.getByPlaceholderText('e.g. MT 4 - RACHHPAL'), 'MT 4 - RACHHPAL');
    change(screen.getByPlaceholderText('e.g. AUH Yard'), 'AUH Yard');
    change(screen.getByPlaceholderText('e.g. JiuJitsu Arena'), 'Dubai Marina');
    change(screen.getByPlaceholderText('e.g. Mohammed / +971 50 123'), 'Mohammed / +971 50 123');
    change(screen.getByPlaceholderText('e.g. Katch Events'), 'Katch Events');
    change(screen.getByLabelText('Time*'), '08:30');
    fireEvent.click(screen.getByText('MT 4 [S]'));
    fireEvent.click(screen.getByText('BG'));
    fireEvent.click(screen.getByText(/F-1 .* JLG 660SJ/));
    const submit = screen.getByRole('button', { name: 'Create Transport Job' });
    fireEvent.click(submit);
    fireEvent.click(submit);
    await waitFor(() => expect(onClose).toHaveBeenCalled());
    expect(createMutateAsync).toHaveBeenCalledTimes(1);
    const { body, submissionId } = createMutateAsync.mock.calls[0][0];
    expect(submissionId).toBeTruthy();
    expect(body).toMatchObject({
      machineId: 'm-f1', plannerName: 'Prashanth', shift: 'Morning', transportTeam: 'MT 4 - RACHHPAL', scheduleSerial: 1,
      origin: 'AUH Yard', destination: 'Dubai Marina', transportText: 'MT 4 [S]', typeCode: 'D',
      contactText: 'Mohammed / +971 50 123', salespersonCode: 'BG', clientText: 'Katch Events', remarks: null,
    });
    expect(typeof body.scheduledAt).toBe('string');
  });

  it('keeps the entered values when the server rejects the job', async () => {
    createMutateAsync.mockRejectedValue(new Error('storage full'));
    const onClose = vi.fn();
    render(<TransportJobDialog open onClose={onClose} />);
    change(screen.getByPlaceholderText('e.g. Prashanth'), 'Prashanth');
    change(screen.getByPlaceholderText('e.g. MT 4 - RACHHPAL'), 'MT 4 - RACHHPAL');
    change(screen.getByPlaceholderText('e.g. AUH Yard'), 'AUH Yard');
    change(screen.getByPlaceholderText('e.g. JiuJitsu Arena'), 'Dubai Marina');
    change(screen.getByPlaceholderText('e.g. Mohammed / +971 50 123'), 'Mohammed / +971 50 123');
    change(screen.getByPlaceholderText('e.g. Katch Events'), 'Katch Events');
    change(screen.getByLabelText('Time*'), '08:30');
    fireEvent.click(screen.getByText('MT 4 [S]'));
    fireEvent.click(screen.getByText('BG'));
    fireEvent.click(screen.getByText(/F-1 .* JLG 660SJ/));
    fireEvent.click(screen.getByRole('button', { name: 'Create Transport Job' }));
    expect(await screen.findByTestId('api-error')).toBeTruthy();
    expect(onClose).not.toHaveBeenCalled();
    expect((screen.getByPlaceholderText('e.g. Prashanth') as HTMLInputElement).value).toBe('Prashanth');
  });
});

describe('TransportPage', () => {
  it('lists manual and collection-generated jobs in one list without truncation', async () => {
    jobs = Array.from({ length: 10 }, (_, i) =>
      job({ id: `j-${i}`, reference: `TJ-2026-${String(10 - i).padStart(4, '0')}`, autoGenerated: i === 3, type: i === 3 ? 'Collection' : 'Delivery' }));
    render(<TransportPage />);
    const refs = await screen.findAllByText(/^TJ-\d{4}-\d{4}$/);
    expect(refs).toHaveLength(10);
  });

  it('opens the detail panel with the 15 REF-13 rows', async () => {
    jobs = [job({ id: 'j-1', reference: 'TJ-2026-0001' })];
    render(<TransportPage />);
    fireEvent.click(await screen.findByText('TJ-2026-0001', { selector: 'p' }));
    const dialog = await panel();
    for (const label of ['Planner Name', 'Date', 'Shift', 'Transport Team', 'Sr. No', 'Fleet', 'From', 'To',
      'Transport', 'Type', 'Contact', 'Sales', 'Client', 'Time', 'Remarks']) {
      expect(within(dialog).getAllByText(label, { exact: true }).length).toBeGreaterThan(0);
    }
    expect(within(dialog).getByText('Dubai Marina')).toBeTruthy();
    expect(within(dialog).getByText('Katch Events')).toBeTruthy();
  });

  it('changes status through the status endpoint with the row version', async () => {
    jobs = [job({ id: 'j-1', reference: 'TJ-2026-0001', rowVersion: 5 })];
    render(<TransportPage />);
    fireEvent.click(await screen.findByText('TJ-2026-0001', { selector: 'p' }));
    const dialog = await panel();
    fireEvent.click(within(dialog).getByText('Loading'));
    expect(statusMutate).toHaveBeenCalledTimes(1);
    expect(statusMutate.mock.calls[0][0]).toEqual({ id: 'j-1', rowVersion: 5, status: 'Loading' });
    expect(updateMutate).not.toHaveBeenCalled();
  });

  it('assigns a driver with an If-Match update', async () => {
    jobs = [job({ id: 'j-1', reference: 'TJ-2026-0001', rowVersion: 5 })];
    render(<TransportPage />);
    fireEvent.click(await screen.findByText('TJ-2026-0001', { selector: 'p' }));
    const dialog = await panel();
    fireEvent.click(within(dialog).getByText(/Rachhpal/));
    expect(updateMutate.mock.calls[0][0]).toEqual({ id: 'j-1', rowVersion: 5, patch: { driverId: 'd-1' } });
  });
});
