import { BaseEntity, ID, ISODate } from './common';

export interface Driver {
  id: ID;
  name: string;
  phone: string;
  licenseNumber: string;
  licenseExpiry: ISODate;
  branchId: ID;
  branchName: string;
  status: 'Available' | 'On Delivery' | 'Returning' | 'Off Duty';
  rating: number;
  totalDeliveries: number;
  currentTruckId?: ID;
}

export interface Truck {
  id: ID;
  registration: string;
  type: 'Flatbed' | 'Lowboy' | 'Crane Truck' | 'Recovery';
  capacity: number;
  branchId: ID;
  branchName: string;
  status: 'Available' | 'On Route' | 'Maintenance' | 'Offline';
  currentDriverId?: ID;
  currentDriverName?: string;
}

export type TransportJobStatus =
  | 'Scheduled'
  | 'Loading'
  | 'In Transit'
  | 'Delivered'
  | 'Returning'
  | 'Completed'
  | 'Cancelled';

export interface TransportJob extends BaseEntity {
  reference: string;
  machineId: ID;
  assetNumber: string;
  machineModel: string;
  branchId: ID;
  branchName: string;
  driverId: ID;
  driverName: string;
  truckId: ID;
  truckRegistration: string;
  origin: string;
  destination: string;
  scheduledTime: ISODate;
  status: TransportJobStatus;
  distance?: number;
  bookingRef?: string;
  type: 'Delivery' | 'Collection' | 'Transfer';
  notes?: string;
  
  // Financial tracking for TRIPBASE report
  customerName?: string;      // Who's being charged
  chargeToCustomer: number;   // Transport fee charged (ex-VAT)
  internalCost: number;       // Actual cost (fuel + wages + tolls)
}

// -- REF-13 transport schedule (persisted per company) -----------------------

export type TransportShift = 'Morning' | 'Evening';
export type TransportTypeCode = 'D' | 'T' | 'O' | 'T2';

/** The 15 REF-13 form fields exactly as entered. */
export interface TransportForm {
  plannerName: string;
  date: string;
  shift: TransportShift;
  transportTeam: string;
  srNo: number;
  fleet: string;
  from: string;
  to: string;
  transport: string;
  type: TransportTypeCode;
  contact: string;
  sales: string;
  client: string;
  time: string;
  remarks?: string;
}

/** One persisted job. All companies share one array, rows carry orgId. */
export interface TransportJobRecord extends TransportForm {
  id: string;
  orgId: string;
  /** TJ-<year>-NNNN */
  reference: string;
  status: TransportJobStatus;
  machineId?: string;
  branchId?: string;
  branchName?: string;
  driverId?: string;
  driverName?: string;
  truckId?: string;
  quotationId?: string;
  bookingId?: string;
  collectionNoteId?: string;
  /** Legacy reference (for example the collection note number). */
  sourceRef?: string;
  autoGenerated?: boolean;
  seedKey?: string;
  createdAt: string;
  updatedAt: string;
}

/** What every list consumer reads. */
export interface TransportJobView extends TransportJob {
  /** Present for persisted rows, absent for mock rows. */
  ref13?: TransportForm;
  orgId: string;
  quotationId?: string;
  collectionNoteId?: string;
}

/** Local changes to a mock row, kept in the store. */
export interface JobOverride {
  status?: TransportJobStatus;
  driverId?: string;
  driverName?: string;
}

export type JobPatch = Partial<
  Pick<TransportJobRecord, 'status' | 'driverId' | 'driverName' | 'truckId' | 'remarks'>
>;
