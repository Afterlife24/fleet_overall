/**
 * appStore.ts — Central Zustand store with localStorage persistence
 *
 * This is the "backend substitute" — it holds all user-created records
 * and enforces the state machine transitions from overview.md §4.
 *
 * State Machine (§4.1):
 *   Gate IN → PHI → UR/WIP → PDI → Available → Allocated → On Hire
 *   On Hire → Breakdown (stays On Hire, clock starts)
 *   On Hire → Gate IN (Off Hire) → PHI (cycle repeats)
 *
 * When backend is ready: replace each action with an API call.
 * The signatures stay the same — no page changes needed.
 */

import { create } from 'zustand';
import { persist } from 'zustand/middleware';
import { MachineStatus } from '@/types/machine';
import { machines as mockMachines } from '@/services/mock/machines';
import { transportJobs as mockTransportJobs } from '@/services/mock/transport';
import { gateEntries as mockGateEntries } from '@/services/mock/gate';
import { breakdowns as mockBreakdowns } from '@/services/mock/breakdowns';

