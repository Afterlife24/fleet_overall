// ── State Machine Helpers ──────────────────────────────────────────────────

export function getMachineStatus(
  machineId: string,
  overrides: MachineOverride[]
): MachineStatus {
  const override = overrides.find(o => o.machineId === machineId);
  if (override) return override.status;
  const mock = mockMachines.find(m => m.id === machineId);
  return mock?.status ?? 'Available';
}

// ── Store ──────────────────────────────────────────────────────────────────

interface AppState {
  // Machine status overrides (real-time state changes)
  machineOverrides: MachineOverride[];

  // User-created records
  jobCards: StoredJobCard[];
  inspections: StoredInspection[];
  transportJobs: StoredTransportJob[];
  gateEntries: StoredGateEntry[];
  breakdowns: StoredBreakdown[];

  // ── Machine Status Actions ──
  setMachineStatus: (machineId: string, status: MachineStatus, reason?: string, meta?: Partial<MachineOverride>) => void;
  getMachineCurrentStatus: (machineId: string) => MachineStatus;

  // ── Job Cards ──
  addJobCard: (jc: StoredJobCard) => void;
  updateJobCard: (id: string, data: Partial<StoredJobCard>) => void;
  getAllJobCards: () => StoredJobCard[];

  // ── Inspections ──
  addInspection: (insp: StoredInspection) => void;
  updateInspection: (id: string, data: Partial<StoredInspection>) => void;
  getAllInspections: (type?: StoredInspection['type']) => StoredInspection[];

  // ── Transport Jobs ──
  addTransportJob: (tj: StoredTransportJob) => void;
  updateTransportJob: (id: string, data: Partial<StoredTransportJob>) => void;
  getAllTransportJobs: () => StoredTransportJob[];

  // ── Gate Entries ──
  addGateEntry: (ge: StoredGateEntry) => void;
  updateGateEntry: (id: string, data: Partial<StoredGateEntry>) => void;
  getAllGateEntries: () => StoredGateEntry[];

  // ── Breakdowns ──
  addBreakdown: (bd: StoredBreakdown) => void;
  updateBreakdown: (id: string, data: Partial<StoredBreakdown>) => void;
  getAllBreakdowns: () => StoredBreakdown[];

  // ── Workflow Helpers ──
  // Find active booking for a machine (from bookingStore)
  getActiveBookingForMachine: (machineId: string) => any | undefined;
}

export const useAppStore = create<AppState>()(
  persist(
    (set, get) => ({
      machineOverrides: [],
      jobCards: [],
      inspections: [],
      transportJobs: [],
      gateEntries: [],
      breakdowns: [],

      // ── Machine status ──
      setMachineStatus: (machineId, status, reason, meta = {}) => {
        const now = new Date().toISOString();
        set(state => {
          const existing = state.machineOverrides.findIndex(o => o.machineId === machineId);
          const override: MachineOverride = {
            machineId,
            status,
            updatedAt: now,
            reason,
            ...meta,
          };
          if (existing >= 0) {
            const next = [...state.machineOverrides];
            next[existing] = override;
            return { machineOverrides: next };
          }
          return { machineOverrides: [...state.machineOverrides, override] };
        });
      },

      getMachineCurrentStatus: (machineId) => {
        return getMachineStatus(machineId, get().machineOverrides);
      },

      // ── Job Cards ──
      addJobCard: (jc) => set(s => ({ jobCards: [jc, ...s.jobCards] })),
      updateJobCard: (id, data) => set(s => ({
        jobCards: s.jobCards.map(j => j.id === id ? { ...j, ...data, updatedAt: new Date().toISOString() } : j),
      })),
      getAllJobCards: () => {
        // merge mock + user-created
        const user = get().jobCards;
        return [...user];
      },

      // ── Inspections ──
      addInspection: (insp) => set(s => ({ inspections: [insp, ...s.inspections] })),
      updateInspection: (id, data) => set(s => ({
        inspections: s.inspections.map(i => i.id === id ? { ...i, ...data, updatedAt: new Date().toISOString() } : i),
      })),
      getAllInspections: (type) => {
        const user = get().inspections;
        return type ? user.filter(i => i.type === type) : user;
      },

      // ── Transport Jobs ──
      addTransportJob: (tj) => set(s => ({ transportJobs: [tj, ...s.transportJobs] })),
      updateTransportJob: (id, data) => set(s => ({
        transportJobs: s.transportJobs.map(t => t.id === id ? { ...t, ...data, updatedAt: new Date().toISOString() } : t),
      })),
      getAllTransportJobs: () => get().transportJobs,

      // ── Gate Entries ──
      addGateEntry: (ge) => set(s => ({ gateEntries: [ge, ...s.gateEntries] })),
      updateGateEntry: (id, data) => set(s => ({
        gateEntries: s.gateEntries.map(g => g.id === id ? { ...g, ...data, updatedAt: new Date().toISOString() } : g),
      })),
      getAllGateEntries: () => {
        const user = get().gateEntries;
        return [...user, ...(mockGateEntries as unknown as StoredGateEntry[])];
      },

      // ── Breakdowns ──
      addBreakdown: (bd) => set(s => ({ breakdowns: [bd, ...s.breakdowns] })),
      updateBreakdown: (id, data) => set(s => ({
        breakdowns: s.breakdowns.map(b => b.id === id ? { ...b, ...data, updatedAt: new Date().toISOString() } : b),
      })),
      getAllBreakdowns: () => {
        const user = get().breakdowns;
        return [...user, ...(mockBreakdowns as unknown as StoredBreakdown[])];
      },

      // ── Workflow Helper ──
      getActiveBookingForMachine: (machineId) => {
        // import inline to avoid circular deps — reads from bookingStore via localStorage
        try {
          const raw = localStorage.getItem('fleet-bookings-v1');
          if (!raw) return undefined;
          const parsed = JSON.parse(raw);
          const allBookings: any[] = [
            ...(parsed?.state?.userBookings ?? []),
          ];
          const today = new Date().toISOString().split('T')[0];
          return allBookings.find(b =>
            b.machineId === machineId &&
            b.startDate <= today &&
            b.endDate >= today &&
            !['Cancelled', 'Returned'].includes(b.status)
          );
        } catch {
          return undefined;
        }
      },
    }),
    { name: 'fleet-app-store-v1' }
  )
);
