// T11 (transport persistence) and T12 (collection without an invoice, repeat initiation) against fleet_test.
import { randomUUID } from 'node:crypto';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createHarness, type Actor, type Harness } from './apiHarness.js';
import {
  getBooking, initiateCollection, jobBody, moveJob, newBooking, newMachine, quotationPhase, rentalChain, startHire, type Chain,
} from './rentalFixtures.js';

let h: Harness;
let admin: Actor; // managing-director
let session2: Actor; // a second session (another user) of the same company

beforeAll(async () => {
  h = await createHarness();
  admin = await h.actor('tc-admin', 'managing-director');
  session2 = await h.addUser(admin, { roleCode: 'operations-manager', branchId: admin.branchId, allBranches: true });
});
afterAll(async () => {
  await h.close();
});

async function onHire(opts: Parameters<typeof rentalChain>[2] = {}): Promise<Chain> {
  const c = await rentalChain(h, admin, opts);
  const res = await startHire(h, admin, c.booking.id, c.booking.rowVersion);
  expect(res.status, JSON.stringify(res.body)).toBe(200);
  return { ...c, booking: res.body };
}

describe('T11 manual and collection-generated transport persist identically', () => {
  it('stores drivers, vehicles and a one-machine job with every REF-13 field; another session reads the same values', async () => {
    const driver = await h.create(admin, '/drivers', { branchId: admin.branchId, name: 'Ali Driver', phone: '+971 50 111 1111', licenseNo: 'LIC-1', licenseExpiresOn: '2031-01-01' });
    expect(driver.status, JSON.stringify(driver.body)).toBe(201);
    const vehicle = await h.create(admin, '/transport-vehicles', { branchId: admin.branchId, registrationNo: `DXB ${randomUUID().slice(0, 6)}`, vehicleType: 'Flatbed', capacityKg: '12000' });
    expect(vehicle.status, JSON.stringify(vehicle.body)).toBe(201);
    expect((await h.create(admin, '/transport-vehicles', { branchId: admin.branchId, registrationNo: vehicle.body.registrationNo, vehicleType: 'Flatbed', capacityKg: '1' })).status).toBe(409);

    const c = await rentalChain(h, admin);
    const body = jobBody(c.machine.id, {
      bookingId: c.booking.id, quotationId: c.quotation.id, driverId: driver.body.id, vehicleId: vehicle.body.id,
      scheduleSerial: 7, shift: 'Evening', typeCode: 'T2', distanceKm: '12.5', chargeToCustomer: '350', internalCost: '120.25', remarks: 'Call before arrival',
    });
    const created = await h.create(admin, '/transport-jobs', body);
    expect(created.status, JSON.stringify(created.body)).toBe(201);
    const job = created.body;
    expect(job).toMatchObject({
      machineId: c.machine.id, bookingId: c.booking.id, quotationId: c.quotation.id, driverId: driver.body.id, vehicleId: vehicle.body.id,
      plannerName: 'Planner One', scheduleDate: '2030-03-01', shift: 'Evening', transportTeam: 'Team A', scheduleSerial: 7,
      fleetNoSnapshot: c.machine.fleetNo, origin: 'Main yard', destination: 'Jebel Ali site', transportText: 'Delivery of boom lift',
      typeCode: 'T2', contactText: '+971 50 000 0000', salespersonCode: 'SP1', clientText: 'Client Co', status: 'Scheduled',
      distanceKm: '12.500', chargeToCustomer: '350.000000', internalCost: '120.250000', currencyCode: 'AED', autoGenerated: false,
      collectionNoteId: null, remarks: 'Call before arrival',
    });
    expect(job.reference).toMatch(/^TR-\d{4}\d{4,}$/);
    expect(new Date(job.scheduledAt).toISOString()).toBe('2030-03-01T04:00:00.000Z');

    // Another session: detail, list and filters return the same record and counts.
    const detail = await h.call(session2, 'get', `/transport-jobs/${job.id}`);
    expect(detail.status).toBe(200);
    expect(detail.body).toEqual(job);
    const list = await h.call(session2, 'get', `/transport-jobs?bookingId=${c.booking.id}`);
    expect(list.body).toMatchObject({ total: 1, items: [job] });
    const before = (await h.call(session2, 'get', '/transport-jobs?status=Scheduled')).body.total;
    const scheduledJobs = await h.call(admin, 'get', '/transport-jobs?status=Scheduled');
    expect(scheduledJobs.body.total).toBe(before);
    expect((await h.call(session2, 'get', '/drivers')).body.items.map((d: { id: string }) => d.id)).toContain(driver.body.id);
    expect((await h.call(session2, 'get', `/transport-vehicles?q=${encodeURIComponent(vehicle.body.registrationNo)}`)).body.total).toBe(1);

    // Updates and status moves persist and move the counters; the quotation phase is never touched by transport status.
    const upd = await h.change(admin, 'patch', `/transport-jobs/${job.id}`, job.rowVersion, { destination: 'Dubai Marina', chargeToCustomer: null });
    expect(upd.status).toBe(200);
    expect((await h.call(session2, 'get', `/transport-jobs/${job.id}`)).body).toMatchObject({ destination: 'Dubai Marina', chargeToCustomer: null, rowVersion: upd.body.rowVersion });
    const phaseBefore = await quotationPhase(h, admin, c.quotation.id);
    await moveJob(h, admin, upd.body, 'In Transit');
    expect((await h.call(session2, 'get', '/transport-jobs?status=In%20Transit')).body.items.map((j: { id: string }) => j.id)).toContain(job.id);
    expect((await h.call(session2, 'get', '/transport-jobs?status=Scheduled')).body.total).toBe(before - 1);
    expect(await quotationPhase(h, admin, c.quotation.id)).toBe(phaseBefore);
  });

  it('rejects mismatched booking, quotation and illegal status moves; a completed job is final', async () => {
    const c = await rentalChain(h, admin);
    const other = await newMachine(h, admin);
    const wrongMachine = await h.create(admin, '/transport-jobs', jobBody(other.id, { bookingId: c.booking.id }));
    expect(wrongMachine.status).toBe(422);
    expect(wrongMachine.body.fieldErrors.bookingId).toBe('machine_mismatch');
    const otherChain = await rentalChain(h, admin);
    const wrongQuote = await h.create(admin, '/transport-jobs', jobBody(c.machine.id, { bookingId: c.booking.id, quotationId: otherChain.quotation.id }));
    expect(wrongQuote.status).toBe(422);
    expect(wrongQuote.body.fieldErrors.quotationId).toBe('chain_mismatch');
    expect((await h.create(admin, '/transport-jobs', jobBody(c.machine.id, { scheduledAt: 'tomorrow' }))).status).toBe(422);
    expect((await h.create(admin, '/transport-jobs', jobBody(c.machine.id, { typeCode: 'X' }))).status).toBe(422);

    const job = (await h.create(admin, '/transport-jobs', jobBody(c.machine.id, { bookingId: c.booking.id }))).body;
    const skip = await h.change(admin, 'post', `/transport-jobs/${job.id}/status`, job.rowVersion, { status: 'Delivered' });
    expect(skip.status).toBe(422);
    expect(skip.body.code).toBe('INVALID_TRANSITION');
    await moveJob(h, admin, job, 'Completed');
    const done = (await h.call(admin, 'get', `/transport-jobs/${job.id}`)).body;
    expect(done.status).toBe('Completed');
    expect((await h.change(admin, 'patch', `/transport-jobs/${job.id}`, done.rowVersion, { remarks: 'late' })).status).toBe(422);
    expect((await h.change(admin, 'post', `/transport-jobs/${job.id}/status`, done.rowVersion, { status: 'Cancelled' })).status).toBe(422);
  });
});

describe('T12 collection without an invoice and repeat initiation', () => {
  it('creates one linked note, MQD, service report and transport job atomically; the invoice is optional', async () => {
    const c = await onHire();
    const manual = await h.create(admin, '/transport-jobs', jobBody(c.machine.id, { bookingId: c.booking.id }));
    expect(manual.status).toBe(201);

    const res = await initiateCollection(h, admin, c.booking.id, { collectionAddress: 'Customer site gate 2', remarks: 'Handle with care' });
    expect(res.status, JSON.stringify(res.body)).toBe(201);
    const { collectionNote: cn, mqdReport: mqd, serviceReport: tps, transportJob: job } = res.body;
    expect(cn).toMatchObject({
      bookingId: c.booking.id, machineId: c.machine.id, status: 'Draft', relatedInvoiceId: null, collectionAddress: 'Customer site gate 2',
      pickedUpAt: null, collectedAt: null,
    });
    expect(cn.number).toMatch(/^CN-\d{4}\d{4,}$/);
    expect(mqd).toMatchObject({ bookingId: c.booking.id, collectionNoteId: cn.id, phase: 'COLLECTION' });
    expect(mqd.fields).toMatchObject({ collectionNoteNumber: cn.number, bookingReference: c.booking.reference, fleetNo: c.machine.fleetNo, site: 'Customer site gate 2' });
    expect(tps).toMatchObject({ bookingId: c.booking.id, collectionNoteId: cn.id, phase: 'COLLECTION' });
    expect(job).toMatchObject({
      bookingId: c.booking.id, machineId: c.machine.id, collectionNoteId: cn.id, quotationId: c.quotation.id, autoGenerated: true,
      sourceKey: `collection:${cn.id}`, status: 'Scheduled', origin: 'Customer site gate 2',
    });
    // Collection requested; the machine has not come back (pickup and receipt are separate facts).
    const booking = await getBooking(h, admin, c.booking.id);
    expect(booking).toMatchObject({ status: 'On Hire', returnedAt: null, physicallyOccupied: true });
    expect(booking).toMatchObject({ offHireRequestedAt: expect.any(String) });

    // The manual and the collection job are in one persistent list, visible to another session.
    const list = await h.call(session2, 'get', `/transport-jobs?bookingId=${c.booking.id}`);
    expect(list.body.total).toBe(2);
    expect(list.body.items.map((j: { autoGenerated: boolean }) => j.autoGenerated).sort()).toEqual([false, true]);
    expect((await h.call(session2, 'get', `/transport-jobs?bookingId=${c.booking.id}&autoGenerated=true`)).body.items[0].id).toBe(job.id);
    const read = await h.call(session2, 'get', `/collection-notes/${cn.id}`);
    expect(read.body).toEqual(res.body);
    expect((await h.call(session2, 'get', `/collection-notes?bookingId=${c.booking.id}`)).body.total).toBe(1);
  });

  it('repeat and concurrent initiation leave exactly one open note, report set and job', async () => {
    const c = await onHire();
    const key = randomUUID();
    const first = await initiateCollection(h, admin, c.booking.id, {}, key);
    expect(first.status).toBe(201);
    const sameKey = await initiateCollection(h, admin, c.booking.id, {}, key);
    const newKey = await initiateCollection(h, admin, c.booking.id, {});
    expect(sameKey.body).toEqual(first.body);
    expect(newKey.status).toBe(200);
    expect(newKey.body.collectionNote.id).toBe(first.body.collectionNote.id);
    expect(newKey.body.transportJob.id).toBe(first.body.transportJob.id);

    const racing = await onHire();
    const results = await Promise.all(Array.from({ length: 4 }, () => initiateCollection(h, admin, racing.booking.id)));
    expect(results.map((r) => r.status).sort()).toEqual([200, 200, 200, 201]);
    expect(new Set(results.map((r) => r.body.collectionNote.id)).size).toBe(1);
    for (const table of ['collection_notes', 'mqd_reports', 'third_party_service_reports', 'transport_jobs']) {
      const rows = await h.sql(admin, `SELECT 1 FROM ${table} WHERE booking_id = $1`, [racing.booking.id]);
      expect(rows, table).toHaveLength(1);
    }
    // Numbers: no gaps caused by the losing requests.
    const numbers = await h.sql<{ next_value: string }>(admin, "SELECT next_value FROM number_sequences WHERE sequence_kind = 'CN' ORDER BY next_value");
    expect(numbers.length).toBeGreaterThan(0);
  });

  it('an invoice reference must be an invoice of the booking quotation; the note is created without any invoice', async () => {
    const c = await onHire();
    const other = await onHire();
    const mk = async (cc: Chain) => {
      const res = await h.create(admin, '/invoices', {
        quotationId: cc.quotation.id, hireAgreementId: cc.agreement.id, invoiceType: 'Continuous Hire', periodStart: '2030-03-01',
        periodEnd: '2030-03-31', equipment: { quantity: '1', unitRate: '1000', amount: '1000' }, periodChargeConfirmed: true,
      });
      expect(res.status, JSON.stringify(res.body)).toBe(201);
      return res.body.id as string;
    };
    const foreignInvoice = await mk(other);
    const own = await mk(c);
    const bad = await initiateCollection(h, admin, c.booking.id, { relatedInvoiceId: foreignInvoice });
    expect(bad.status).toBe(422);
    expect(bad.body.fieldErrors.relatedInvoiceId).toBe('not_booking_invoice');
    expect(await h.sql(admin, 'SELECT 1 FROM collection_notes WHERE booking_id = $1', [c.booking.id])).toHaveLength(0);
    const ok = await initiateCollection(h, admin, c.booking.id, { relatedInvoiceId: own });
    expect(ok.status).toBe(201);
    expect(ok.body.collectionNote.relatedInvoiceId).toBe(own);
    const clear = await h.change(admin, 'patch', `/collection-notes/${ok.body.collectionNote.id}`, ok.body.collectionNote.rowVersion, { relatedInvoiceId: foreignInvoice });
    expect(clear.status).toBe(422);
    const unlink = await h.change(admin, 'patch', `/collection-notes/${ok.body.collectionNote.id}`, ok.body.collectionNote.rowVersion, { relatedInvoiceId: null });
    expect(unlink.status).toBe(200);
    expect(unlink.body.collectionNote.relatedInvoiceId).toBeNull();
  });

  it('refuses a booking that is not On Hire; pickup is not a return; cancelling releases the job and allows a fresh request', async () => {
    const idle = await rentalChain(h, admin);
    const refused = await initiateCollection(h, admin, idle.booking.id);
    expect(refused.status).toBe(422);
    expect(refused.body.fieldErrors.bookingId).toBe('not_on_hire');
    expect(await h.sql(admin, 'SELECT 1 FROM collection_notes WHERE booking_id = $1', [idle.booking.id])).toHaveLength(0);

    const c = await onHire();
    const created = await initiateCollection(h, admin, c.booking.id, { scheduledCollectionAt: '2030-04-02T09:00:00+04:00' });
    expect(created.body.collectionNote.status).toBe('Scheduled');
    const cn = created.body.collectionNote;
    const picked = await h.change(admin, 'post', `/collection-notes/${cn.id}/picked-up`, cn.rowVersion, {});
    expect(picked.status).toBe(200);
    expect(picked.body.collectionNote).toMatchObject({ status: 'Picked Up', collectedAt: null, pickedUpAt: expect.any(String) });
    expect(await getBooking(h, admin, c.booking.id)).toMatchObject({ status: 'On Hire', returnedAt: null, physicallyOccupied: true });

    const cancelled = await h.change(admin, 'post', `/collection-notes/${cn.id}/cancel`, picked.body.collectionNote.rowVersion, { reason: 'Truck broke down' });
    expect(cancelled.status).toBe(200);
    expect(cancelled.body.transportJob.status).toBe('Cancelled');
    const again = await initiateCollection(h, admin, c.booking.id);
    expect(again.status).toBe(201);
    expect(again.body.collectionNote.id).not.toBe(cn.id);
    expect((await newBooking(h, admin, (await newMachine(h, admin)).id, c.customer.id)).status).toBe('Draft'); // unrelated create unaffected
  });
});
